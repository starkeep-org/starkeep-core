#!/bin/sh
# Regenerates models/*.cfg. Each line of the table: name | invariants | overrides.
# Defaults: one device, one record key, one label key, two writes, Limit 2.
cd "$(dirname "$0")"
mkdir -p models
SAFE="TypeOK DeviceNoGap CloudNoLoss CloudCoverageHonestAtRest"
LOSS="TypeOK DeviceNoGap CloudNoLoss"
mk() {
  name=$1; inv=$2; shift 2
  {
    echo "\\* Generated by gen-models.sh: $name"
    echo "SPECIFICATION Spec"
    echo "CONSTANTS"
    for kv in NumNodes=1 NumRec=1 NumLab=1 MaxTime=2 MaxWrites=2 Limit=2 BatchMax=1 MaxCrashes=0 "Writers={1}" RealTimeHLC=TRUE MergedApply=TRUE ApplyUnit=\"timestamp\" GuardedWrite=TRUE MutPerStreamCeiling=FALSE MutSplitTimestamps=FALSE MutNoTrim=FALSE MutNoCoverageCap=FALSE; do
      k=${kv%%=*}; v=${kv#*=}
      for o in "$@"; do [ "${o%%=*}" = "$k" ] && v=${o#*=}; done
      echo "  $k = $v"
    done
    echo "INVARIANTS"
    for i in $inv; do echo "  $i"; done
  } > "models/$name.cfg"
}
# --- Findings: the responder as written today (records, then labels).
mk finding-crash         "$LOSS" MergedApply=FALSE ApplyUnit=\"statement\" GuardedWrite=FALSE MaxCrashes=1
mk finding-concurrent    "$LOSS" MergedApply=FALSE ApplyUnit=\"statement\" GuardedWrite=FALSE NumNodes=2
# --- Merged order alone is not enough: one HLC split across two statements.
mk finding-batch-crash      "$LOSS" ApplyUnit=\"statement\" GuardedWrite=FALSE NumRec=2 NumLab=0 MaxTime=1 MaxWrites=1 BatchMax=2 MaxCrashes=1
mk finding-batch-concurrent "$LOSS" ApplyUnit=\"statement\" GuardedWrite=FALSE NumNodes=2 NumRec=2 NumLab=0 MaxTime=1 MaxWrites=1 BatchMax=2
# --- The LWW check and the write are separate transactions: a lost update.
mk finding-lww-race      "$LOSS" ApplyUnit=\"statement\" GuardedWrite=FALSE NumNodes=2 "Writers={1,2}" NumLab=0
# --- The same shapes with the fix: merged per-author HLC order, one transaction per HLC.
mk fixed-crash           "$SAFE" MaxCrashes=1
mk fixed-concurrent      "$SAFE" NumNodes=2
# --- Wider checks of the fixed protocol.
mk fixed-batches         "$SAFE" NumRec=3 MaxTime=3 MaxWrites=3 BatchMax=2 MaxCrashes=1
mk fixed-labelbatch      "$SAFE" NumNodes=2 NumLab=2 MaxTime=2 BatchMax=2 Limit=1 MaxCrashes=1
mk fixed-two-writers     "$SAFE" NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=1 MaxCrashes=1
mk fixed-hlc-skew        "$SAFE" NumNodes=2 "Writers={1,2}" MaxTime=4 MaxWrites=3 Limit=1 RealTimeHLC=FALSE
mk fixed-relay           "$SAFE" NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=2 BatchMax=2 MaxCrashes=1
# --- The DSQL-friendly fix: per-row writes, coverage raised after each whole HLC,
#     and the cloud's scans capped at its own coverage. No large transactions.
mk deferred-crash        "$SAFE" ApplyUnit=\"deferred\" MaxCrashes=1
mk deferred-concurrent   "$SAFE" ApplyUnit=\"deferred\" NumNodes=2
mk deferred-batch-crash  "$SAFE" ApplyUnit=\"deferred\" NumRec=2 NumLab=0 MaxTime=1 MaxWrites=1 BatchMax=2 MaxCrashes=1
mk deferred-batch-concurrent "$SAFE" ApplyUnit=\"deferred\" NumNodes=2 NumRec=2 NumLab=0 MaxTime=1 MaxWrites=1 BatchMax=2
mk deferred-batches      "$SAFE" ApplyUnit=\"deferred\" NumRec=3 MaxTime=3 MaxWrites=3 BatchMax=2 MaxCrashes=1
mk deferred-labelbatch   "$SAFE" ApplyUnit=\"deferred\" NumNodes=2 NumLab=2 MaxTime=2 BatchMax=2 Limit=1 MaxCrashes=1
mk deferred-two-writers  "$SAFE" ApplyUnit=\"deferred\" NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=1 MaxCrashes=1
mk deferred-relay        "$SAFE" ApplyUnit=\"deferred\" NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=2 BatchMax=2
# --- Mutants: each breaks one rule on a shape the fixed protocol passes.
mk mutant-notrim         "$LOSS" NumNodes=2 NumLab=2 MaxTime=1 MaxWrites=1 BatchMax=2 Limit=1 MutNoTrim=TRUE
mk mutant-split          "$LOSS" NumNodes=2 NumLab=2 MaxTime=1 MaxWrites=1 BatchMax=2 Limit=1 MutSplitTimestamps=TRUE
mk mutant-nocap         "$LOSS" ApplyUnit=\"deferred\" MutNoCoverageCap=TRUE NumNodes=2 NumRec=2 NumLab=0 MaxTime=1 MaxWrites=1 BatchMax=2
mk mutant-perstream      "$LOSS" NumRec=3 MaxTime=3 MaxWrites=3 BatchMax=2 MutPerStreamCeiling=TRUE
# --- Witnesses: must be violated, or the clean runs above prove nothing.
mk witness-relayed-label  "WitnessRelayedLabel"   NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=1 MaxCrashes=1
mk witness-truncated      "WitnessTruncatedRound" NumRec=3 MaxTime=3 MaxWrites=3 BatchMax=2 MaxCrashes=1
mk witness-batch          "WitnessBatchDelivered" NumNodes=2 NumLab=2 MaxTime=2 BatchMax=2 Limit=1 MaxCrashes=1
mk witness-crash          "WitnessCrash"          NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=1 MaxCrashes=1
mk witness-converged      "WitnessAllConverged"   NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=1 MaxCrashes=1
