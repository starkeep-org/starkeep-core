#!/bin/sh
# Regenerates models/*.cfg. Each line of the table: name | invariants | overrides.
# Defaults: one device, one record key, one label key, two writes, Limit 2.
cd "$(dirname "$0")"
mkdir -p models
SAFE="TypeOK DeviceNoGap CloudNoLoss CloudCoverageHonestAtRest"
LOSS="TypeOK DeviceNoGap CloudNoLoss"
mk() {
  name=$1; inv=$2; shift 2
  {
    echo "\\* Generated by gen-models.sh: $name"
    echo "SPECIFICATION Spec"
    echo "CONSTANTS"
    for kv in NumNodes=1 NumRec=1 NumLab=1 MaxTime=2 MaxWrites=2 Limit=2 BatchMax=1 MaxCrashes=0 "Writers={1}" RealTimeHLC=TRUE MergedApply=TRUE ApplyUnit=\"timestamp\" DeviceApply=\"atomic\" MaxHalts=0 MaxDeviceFails=0 "DeviceFails={\"rec\"}" BelowBroken=FALSE GuardedWrite=TRUE MutPerStreamCeiling=FALSE MutSplitTimestamps=FALSE MutNoTrim=FALSE MutNoCoverageCap=FALSE; do
      k=${kv%%=*}; v=${kv#*=}
      for o in "$@"; do [ "${o%%=*}" = "$k" ] && v=${o#*=}; done
      echo "  $k = $v"
    done
    echo "INVARIANTS"
    for i in $inv; do echo "  $i"; done
  } > "models/$name.cfg"
}
# --- Before fix B: the responder applied every record, then every label, with
#     its writes guarded (fix A).
mk finding-crash         "$LOSS" MergedApply=FALSE ApplyUnit=\"statement\" GuardedWrite=TRUE MaxCrashes=1
mk finding-concurrent    "$LOSS" MergedApply=FALSE ApplyUnit=\"statement\" GuardedWrite=TRUE NumNodes=2
# --- The responder as written today: merged order (fix B), one statement per
#     row. With every HLC a single row this is safe, which closes finding 1;
#     the state spaces equal fixed-crash and fixed-concurrent, since one row per
#     HLC makes the two apply units the same.
mk merged-crash          "$SAFE" ApplyUnit=\"statement\" MaxCrashes=1
mk merged-concurrent     "$SAFE" ApplyUnit=\"statement\" NumNodes=2
# --- Merged order alone is not enough: one HLC split across two statements.
mk finding-batch-crash      "$LOSS" ApplyUnit=\"statement\" GuardedWrite=TRUE NumRec=2 NumLab=0 MaxTime=1 MaxWrites=1 BatchMax=2 MaxCrashes=1
mk finding-batch-concurrent "$LOSS" ApplyUnit=\"statement\" GuardedWrite=TRUE NumNodes=2 NumRec=2 NumLab=0 MaxTime=1 MaxWrites=1 BatchMax=2
# --- Before fix A: the LWW check and the write were separate transactions.
mk finding-lww-race      "$LOSS" ApplyUnit=\"statement\" GuardedWrite=FALSE NumNodes=2 "Writers={1,2}" NumLab=0
# --- The same shapes with the fix: merged per-author HLC order, one transaction per HLC.
mk fixed-crash           "$SAFE" MaxCrashes=1
mk fixed-concurrent      "$SAFE" NumNodes=2
# --- Wider checks of the fixed protocol.
mk fixed-batches         "$SAFE" NumRec=3 MaxTime=3 MaxWrites=3 BatchMax=2 MaxCrashes=1
mk fixed-labelbatch      "$SAFE" NumNodes=2 NumLab=2 MaxTime=2 BatchMax=2 Limit=1 MaxCrashes=1
mk fixed-two-writers     "$SAFE" NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=1 MaxCrashes=1
mk fixed-hlc-skew        "$SAFE" NumNodes=2 "Writers={1,2}" MaxTime=4 MaxWrites=3 Limit=1 RealTimeHLC=FALSE
mk fixed-relay           "$SAFE" NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=2 BatchMax=2 MaxCrashes=1
# --- The DSQL-friendly fix: per-row writes, coverage raised after each whole HLC,
#     and the cloud's scans capped at its own coverage. No large transactions.
mk deferred-crash        "$SAFE" ApplyUnit=\"deferred\" MaxCrashes=1
mk deferred-concurrent   "$SAFE" ApplyUnit=\"deferred\" NumNodes=2
mk deferred-batch-crash  "$SAFE" ApplyUnit=\"deferred\" NumRec=2 NumLab=0 MaxTime=1 MaxWrites=1 BatchMax=2 MaxCrashes=1
mk deferred-batch-concurrent "$SAFE" ApplyUnit=\"deferred\" NumNodes=2 NumRec=2 NumLab=0 MaxTime=1 MaxWrites=1 BatchMax=2
mk deferred-batches      "$SAFE" ApplyUnit=\"deferred\" NumRec=3 MaxTime=3 MaxWrites=3 BatchMax=2 MaxCrashes=1
mk deferred-labelbatch   "$SAFE" ApplyUnit=\"deferred\" NumNodes=2 NumLab=2 MaxTime=2 BatchMax=2 Limit=1 MaxCrashes=1
mk deferred-two-writers  "$SAFE" ApplyUnit=\"deferred\" NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=1 MaxCrashes=1
mk deferred-relay        "$SAFE" ApplyUnit=\"deferred\" NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=2 BatchMax=2
# --- Apply failures. The cloud halts the failed row's author for the round and
#     carries on with the others (haltedAuthors); the device applies row by
#     row, carries on past a failed row, and holds that author's watermark at
#     the row before it (brokenAt, ownSafeAdvance). All as the code is today.
mk halt-relay            "$SAFE" ApplyUnit=\"statement\" NumNodes=2 "Writers={1,2}" MaxTime=3 MaxWrites=3 Limit=2 MaxHalts=1
mk halt-crash            "$SAFE" ApplyUnit=\"statement\" NumNodes=2 "Writers={1,2}" MaxTime=3 MaxWrites=3 Limit=1 MaxHalts=1 MaxCrashes=1
mk rows-concurrent       "$SAFE" ApplyUnit=\"statement\" DeviceApply=\"rows\" NumNodes=2 "Writers={1,2}" MaxTime=3 MaxWrites=3 Limit=2 MaxCrashes=1
mk rows-fail             "$SAFE" ApplyUnit=\"statement\" DeviceApply=\"rows\" NumNodes=2 "Writers={1,2}" MaxTime=3 MaxWrites=3 Limit=2 MaxDeviceFails=1
#     A record and its labels sharing one HLC, as a delete or restore writes
#     them. The record sorts first and is the only row that can fail, so the
#     row before a failure never shares its HLC.
mk rows-fail-record-batch "$SAFE" DeviceApply=\"rows\" NumNodes=2 NumLab=2 MaxTime=2 MaxWrites=2 BatchMax=3 Limit=3 MaxDeviceFails=1
# --- Finding 4: that holds only because no row that can fail follows another
#     at its HLC. Let a label fail and the device claims it (DeviceNoGap).
mk finding-device-batch  "$LOSS" DeviceApply=\"rows\" NumNodes=2 NumRec=0 NumLab=2 MaxTime=1 MaxWrites=1 BatchMax=2 MaxDeviceFails=1 "DeviceFails={\"rec\",\"lab\"}"
mk fixed-device-batch    "$SAFE" DeviceApply=\"rows\" NumNodes=2 NumRec=0 NumLab=2 MaxTime=1 MaxWrites=1 BatchMax=2 MaxDeviceFails=1 "DeviceFails={\"rec\",\"lab\"}" BelowBroken=TRUE
mk fixed-device-wide     "$SAFE" DeviceApply=\"rows\" NumNodes=2 "Writers={1,2}" NumLab=2 MaxTime=2 MaxWrites=2 BatchMax=2 Limit=2 MaxDeviceFails=1 MaxCrashes=1 "DeviceFails={\"rec\",\"lab\"}" BelowBroken=TRUE
# --- Mutants: each breaks one rule on a shape the fixed protocol passes.
mk mutant-notrim         "$LOSS" NumNodes=2 NumLab=2 MaxTime=1 MaxWrites=1 BatchMax=2 Limit=1 MutNoTrim=TRUE
mk mutant-split          "$LOSS" NumNodes=2 NumLab=2 MaxTime=1 MaxWrites=1 BatchMax=2 Limit=1 MutSplitTimestamps=TRUE
mk mutant-nocap         "$LOSS" ApplyUnit=\"deferred\" MutNoCoverageCap=TRUE NumNodes=2 NumRec=2 NumLab=0 MaxTime=1 MaxWrites=1 BatchMax=2
mk mutant-perstream      "$LOSS" NumRec=3 MaxTime=3 MaxWrites=3 BatchMax=2 MutPerStreamCeiling=TRUE
# --- Witnesses: must be violated, or the clean runs above prove nothing.
mk witness-relayed-label  "WitnessRelayedLabel"   NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=1 MaxCrashes=1
mk witness-truncated      "WitnessTruncatedRound" NumRec=3 MaxTime=3 MaxWrites=3 BatchMax=2 MaxCrashes=1
mk witness-batch          "WitnessBatchDelivered" NumNodes=2 NumLab=2 MaxTime=2 BatchMax=2 Limit=1 MaxCrashes=1
mk witness-crash          "WitnessCrash"          NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=1 MaxCrashes=1
mk witness-converged      "WitnessAllConverged"   NumNodes=2 "Writers={1,2}" NumRec=2 MaxTime=3 MaxWrites=3 Limit=1 MaxCrashes=1
mk witness-halt           "WitnessHalt"           NumNodes=2 "Writers={1,2}" MaxTime=3 MaxWrites=3 Limit=2 MaxHalts=1
mk witness-device-fail    "WitnessDeviceFail"     DeviceApply=\"rows\" NumNodes=2 "Writers={1,2}" MaxTime=3 MaxWrites=3 Limit=2 MaxDeviceFails=1
mk witness-converged-after-failures "WitnessConvergedAfterFailures" DeviceApply=\"rows\" NumNodes=2 "Writers={1,2}" MaxTime=2 MaxWrites=2 Limit=2 MaxHalts=1 MaxDeviceFails=1
